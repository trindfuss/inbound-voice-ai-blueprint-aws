Prompt = Callable[[str], str]

#: The secrets an operator writes (prompts or ``--from-file``); ``basic_auth`` is generated.
WRITABLE: tuple[str, ...] = ("twilio_api_key", "twilio_auth_token")
BASIC_AUTH = "basic_auth"

#: Default length of the overlap in which the previous Basic password is still accepted: 2 h to apply
#: ``post``, 4 h for the longest call the line allows, 2 h margin. Counted from the secret write.
BASIC_OVERLAP_HOURS = 8.0
#: The Basic secret's cache lifetime in seconds (``owlbank.secrets``): how long to wait before ``post``.
BASIC_CACHE_WAIT_S = 60

#: An overlap shorter than this (hours) draws a warning: it may end before the Twilio-side change is
#: applied and the longest call has finished.
SHORT_OVERLAP_HOURS = 6.0

SECOND_ROTATION_WARNING = (
    "WARNING: a second rotation drops the oldest password; if `twilio_setup.py --phase post --apply` has "
    "not run since the last rotation, Twilio still holds a password that will stop working and every new "
    "call will fail until it does")
SHORT_OVERLAP_WARNING = (
    "WARNING: --overlap-hours {hours:g} is shorter than {floor:g}: the previous password may stop being "
    "accepted before the Twilio-side change is applied and the longest call has ended")

#: ``GetRandomPassword`` parameters matching the CDK generator: lower-case hex, 48 characters.
BASIC_PASSWORD_RULES: Mapping[str, Any] = {
    "PasswordLength": 48,
    "ExcludePunctuation": True,
    "ExcludeUppercase": True,
    "IncludeSpace": False,
    "ExcludeCharacters": "ghijklmnopqrstuvwxyz",
}


@dataclass(frozen=True)
class SecretSpec:
    name: str
    output_keys: tuple[str, ...]


SPECS: tuple[SecretSpec, ...] = tuple(SecretSpec(n, keys) for n, keys in SECRET_OUTPUTS.items())


def describe_lengths(value: Mapping[str, str]) -> str:
    return ", ".join(f"{k} ({len(v)} chars)" for k, v in value.items())


def _error_code(exc: Exception) -> str:
    resp = getattr(exc, "response", None)
    if isinstance(resp, dict):
        return str(resp.get("Error", {}).get("Code", type(exc).__name__))
    return type(exc).__name__


# --------------------------------------------------------------------------- values


def check_value(logical: str, value: object) -> dict[str, str]:
    """The schema fields of ``value``, or :class:`ScriptError` naming each problem (never a value)."""
    problems = validate(logical, value)
    if problems:
        raise ScriptError(f"refusing to write {logical}: " + "; ".join(p.describe() for p in problems))
    checked = cast(Mapping[str, str], value)  # no problem: an object whose schema fields are strings
    return {field: checked[field] for field in SCHEMAS[logical]}


def read_file(path: str) -> dict[str, object]:
    """The entries of a ``--from-file`` JSON, refused if group or others may read the file, if it
    isn't a JSON object, or if it has an entry other than :data:`WRITABLE`. No AWS call."""
    try:
        fd = os.open(path, os.O_RDONLY)
    except OSError as exc:
        raise ScriptError(f"--from-file {path}: cannot open ({exc.strerror})") from None
    with os.fdopen(fd, encoding="utf-8") as fh:
        mode = os.fstat(fh.fileno()).st_mode
        if not stat.S_ISREG(mode):
            raise ScriptError(f"--from-file {path}: not a regular file")
        if mode & (stat.S_IRGRP | stat.S_IROTH):
            raise ScriptError(f"--from-file {path}: readable by group or others "
                              f"(mode {stat.S_IMODE(mode):04o}); run chmod 600 on it first")
        try:
            data = json.load(fh)
        except (ValueError, UnicodeDecodeError):
            raise ScriptError(f"--from-file {path}: not valid JSON") from None
    if not isinstance(data, dict):
        raise ScriptError(f"--from-file {path}: expected a JSON object with entries {list(WRITABLE)}")
    unknown = [k for k in data if k not in WRITABLE]
    if unknown:
        hint = " (basic_auth is generated: use --new-basic-password)" if BASIC_AUTH in unknown else ""
        # Entry names aren't echoed: a misplaced value could sit in a key.
        noun = "entry" if len(unknown) == 1 else "entries"
        raise ScriptError(f"--from-file {path}: {len(unknown)} unknown {noun}; "
                          f"only {list(WRITABLE)} are accepted{hint}")
    if not data:
        raise ScriptError(f"--from-file {path}: no entries; nothing to write")
    return {k: data[k] for k in WRITABLE if k in data}


def prompt_values(names: list[str], prompt: Prompt) -> dict[str, dict[str, str]]:
    """One hidden prompt per field of each secret in ``names``; validated."""
    values: dict[str, dict[str, str]] = {}
    for name in names:
        raw = {field: prompt(f"{name} {field}: ").strip() for field in SCHEMAS[name]}
        values[name] = check_value(name, raw)
    return values


# --------------------------------------------------------------------------- AWS


def check_kms(arn: str, sm: Any, kms: Any | None) -> None:
    """Refuse unless the secret is encrypted with a customer-managed KMS key."""
    try:
        desc = sm.describe_secret(SecretId=arn)
    except Exception as exc:
        raise ScriptError(f"describe_secret failed for {arn}: {_error_code(exc)}") from None
    key_id = desc.get("KmsKeyId")
    if not key_id or "alias/aws/" in key_id:
        raise ScriptError(f"{arn} uses the AWS-managed key, not a customer-managed KMS key; refusing")
    if kms is not None:
        try:
            meta = kms.describe_key(KeyId=key_id)["KeyMetadata"]
        except Exception as exc:
            raise ScriptError(f"kms describe_key failed for {arn}: {_error_code(exc)}") from None
        if meta.get("KeyManager") != "CUSTOMER":
            raise ScriptError(f"{arn}: KMS key manager is {meta.get('KeyManager')!r}, "
                              "not CUSTOMER; refusing")


def _read_basic(arn: str, sm: Any) -> dict[str, Any]:
    """The current ``basic_auth`` value as a dict whose ``user`` is valid. The old password and the
    optional pair are not checked here: a rotation replaces them, so a malformed one must not block it.
    :class:`ScriptError` (no value) when the read fails, or the value is the placeholder, not a JSON
    object, or has no valid ``user``."""
    try:
        resp = sm.get_secret_value(SecretId=arn)
    except Exception as exc:  # a client may raise anything; only its code is shown
        raise ScriptError(f"secret {BASIC_AUTH} ({arn}): get_secret_value failed: {_error_code(exc)} "
                          "(the caller needs secretsmanager:GetSecretValue on it and kms:Decrypt on "
                          "its key)") from None
    raw = resp.get("SecretString") if isinstance(resp, Mapping) else None
    try:
        value = json.loads(raw) if isinstance(raw, str) else None
    except ValueError:
        value = None
    ignored = {"password", *OPTIONAL_PAIRS.get(BASIC_AUTH, ())}
    problems = [pr for pr in validate(BASIC_AUTH, value) if pr.field not in ignored]
    if problems:
        raise ScriptError(f"secret {BASIC_AUTH} ({arn}) has no usable user: "
                          + "; ".join(pr.describe() for pr in problems))
    return dict(cast(Mapping[str, Any], value))


def current_basic_user(arn: str, sm: Any) -> str:
    """The ``user`` of the current ``basic_auth`` value (failures as :func:`_read_basic`)."""
    return cast(str, _read_basic(arn, sm)["user"])


def deadline_text(epoch_s: int) -> str:
    """An epoch second as a human time, in UTC."""
    return datetime.fromtimestamp(epoch_s, UTC).strftime("%Y-%m-%d %H:%M:%S UTC")


def _check_basic(value: Mapping[str, Any]) -> dict[str, Any]:
    """``value`` if it is a well-formed ``basic_auth`` secret (pair included), else :class:`ScriptError`
    naming each problem (never a value)."""
    problems = validate(BASIC_AUTH, value)
    if problems:
        raise ScriptError(f"refusing to write {BASIC_AUTH}: " + "; ".join(p.describe() for p in problems))
    return dict(value)


def check_overlap(now: float, overlap_hours: float) -> None:
    """:class:`ScriptError` unless the overlap is a positive finite number of hours whose deadline,
    counted from ``now``, is within :data:`owlbank.secret_schema.MAX_EPOCH_S`."""
    if (isinstance(overlap_hours, bool) or not isinstance(overlap_hours, (int, float))
            or not math.isfinite(overlap_hours) or overlap_hours <= 0):
        raise ScriptError("--overlap-hours must be a positive number")
    if not math.isfinite(now) or now + overlap_hours * 3600 > MAX_EPOCH_S:
        raise ScriptError("--overlap-hours is too large: the deadline would be past the year 2100")


def rotate_basic_value(current: Mapping[str, Any], new_password: object, *, now: float,
                       overlap_hours: float = BASIC_OVERLAP_HOURS) -> dict[str, Any]:
    """The ``basic_auth`` value after a rotation: ``current``'s user, ``new_password`` as the password,
    and ``current``'s password as ``previous_password`` until ``int(now + overlap_hours * 3600)``.

    Whatever previous password ``current`` held is dropped, so a second rotation inside an overlap
    leaves the then-current password as the previous one and at most two passwords are ever stored.
    A current password that is not well formed is not kept as previous (it could not have been
    accepted). :class:`ScriptError` (no value) for an overlap that is not a positive finite number,
    a deadline beyond :data:`owlbank.secret_schema.MAX_EPOCH_S`, or a result that fails the schema.
    """
    check_overlap(now, overlap_hours)
    value: dict[str, Any] = {"user": current.get("user"), "password": new_password}
    old = current.get("password")
    if isinstance(old, str) and not validate(BASIC_AUTH, {"user": value["user"], "password": old}):
        value["previous_password"] = old
        value["previous_until"] = int(now + overlap_hours * 3600)
    return _check_basic(value)


def clear_previous_value(current: Mapping[str, Any]) -> dict[str, Any]:
    """``current`` without the previous password and its deadline; :class:`ScriptError` when what is
    left is not a well-formed ``basic_auth`` secret (clearing must not write an unusable secret)."""
    drop = set(OPTIONAL_PAIRS[BASIC_AUTH])
    return _check_basic({k: v for k, v in current.items() if k not in drop})


def has_active_previous(current: Mapping[str, Any], now: float) -> bool:
    """Whether ``current`` holds a well-formed previous password whose deadline is still ahead."""
    pair = previous_pair(BASIC_AUTH, current)
    return pair is not None and now < pair[1]


def new_basic_auth(arn: str, sm: Any, *, now: float, overlap_hours: float = BASIC_OVERLAP_HOURS,
                   current: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """The rotated ``basic_auth`` value: a fresh ``GetRandomPassword`` password, the old one as previous.
    ``current``: the value already read (else it is read here)."""
    if current is None:
        current = _read_basic(arn, sm)
    try:
        resp = sm.get_random_password(**BASIC_PASSWORD_RULES)
    except Exception as exc:
        raise ScriptError(f"get_random_password failed: {_error_code(exc)}") from None
    password = resp.get("RandomPassword") if isinstance(resp, Mapping) else None
    return rotate_basic_value(current, password, now=now, overlap_hours=overlap_hours)


def cleared_basic_auth(arn: str, sm: Any) -> dict[str, Any]:
    """The current ``basic_auth`` value without the previous password (the rest must be well formed)."""
    return clear_previous_value(_read_basic(arn, sm))


def describe_value(value: Mapping[str, Any]) -> str:
    """Field names with string lengths, and the deadline of a previous password; never a value."""
    parts = []
    for k, v in value.items():
        if isinstance(v, str):
            parts.append(f"{k} ({len(v)} chars)")
        elif k == "previous_until" and isinstance(v, int) and not isinstance(v, bool):
            parts.append(f"{k} ({deadline_text(v)})")
        else:
            parts.append(k)
    return ", ".join(parts)


def rotation_steps(value: Mapping[str, Any], *, dropped_active: bool = False) -> list[str]:
    """The printed next steps after a rotation (``value`` as written); no password text.
    ``dropped_active``: the rotation replaced a previous password that was still accepted."""
    until = value.get("previous_until")
    warn = [f"  {SECOND_ROTATION_WARNING}"] if dropped_active else []
    if not isinstance(until, int):
        return warn + [f"  next: wait about {BASIC_CACHE_WAIT_S} s, then re-run scripts/twilio_setup.py "
                "--phase post --apply (no previous password was kept: the old one was not well formed, "
                "so calls in progress may get 401)"]
    return warn + [f"  apply by {deadline_text(until)}: the previous password is accepted only until then, and "
            "every call fails Basic auth after it",
            f"  next 1: wait about {BASIC_CACHE_WAIT_S} s (the secret cache) before applying",
            "  next 2: re-run scripts/twilio_setup.py --phase post --apply so the number and the "
            "callbacks carry the new password (the Twilio-side update)",
            "  rotating again inside the overlap drops the oldest password: calls started before the "
            "first rotation can then lose callbacks"]


# --------------------------------------------------------------------------- CLI


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="Write the Twilio secrets (hidden prompts or --from-file), or a "
                                            "new Basic password, to Secrets Manager. Dry run by default; "
                                            "values are never printed.")
    add_secret_args(p)
    src = p.add_mutually_exclusive_group()
    src.add_argument("--from-file", metavar="PATH",
                     help=f"JSON with entries {list(WRITABLE)} (chmod 600) instead of prompts")
    src.add_argument("--new-basic-password", action="store_true",
                     help="write a new basic_auth password from GetRandomPassword (48 hex), keeping the "
                          "user; the old password stays accepted as the previous one for --overlap-hours")
    src.add_argument("--clear-previous-basic-password", action="store_true",
                     help="remove the previous basic_auth password (it may stay accepted for up to "
                          f"{BASIC_CACHE_WAIT_S} s: the cache lifetime)")
    p.add_argument("--overlap-hours", type=float, default=None, metavar="N",
                   help="with --new-basic-password: hours the previous password stays accepted "
                        f"(default {BASIC_OVERLAP_HOURS:g}: 2 to apply, 4 for the call limit, 2 margin)")
    p.add_argument("--only", action="append", metavar="NAME", choices=WRITABLE,
                   help=f"prompt only for this secret (repeatable); NAME in {list(WRITABLE)}")
    add_mode_args(p)
    return p


def _fail(exc: ScriptError, step: str, code: int) -> int:
    script_error(log, "populate_secrets", exc, step=step, decision=f"exit_{code}")
    print(f"populate_secrets: {exc}", file=sys.stderr)
    return code


def main(argv: list[str] | None = None, *, sm_client: Any | None = None, kms_client: Any | None = None,
         prompt: Prompt = getpass.getpass, clock: Callable[[], float] = time.time) -> int:
    args = build_parser().parse_args(argv)
    source = ("generate" if args.new_basic_password else "clear" if args.clear_previous_basic_password
              else "file" if args.from_file else "prompt")
    script_start(log, "populate_secrets", mode="apply" if args.apply else "dry_run", source=source,
                 only=sorted(args.only or []))

    # Everything up to the dry-run report is local: no AWS call.
    values: dict[str, dict[str, str]] = {}
    try:
        if args.only and source != "prompt":
            raise ScriptError("--only selects prompts; it can't be combined with --from-file, "
                              "--new-basic-password or --clear-previous-basic-password")
        if args.overlap_hours is not None and source != "generate":
            raise ScriptError("--overlap-hours only goes with --new-basic-password")
        overlap_hours = BASIC_OVERLAP_HOURS if args.overlap_hours is None else args.overlap_hours
        if source == "generate":  # a bad overlap is a usage error: nothing is read or written
            check_overlap(clock(), overlap_hours)
            if overlap_hours < SHORT_OVERLAP_HOURS:
                print(SHORT_OVERLAP_WARNING.format(hours=overlap_hours, floor=SHORT_OVERLAP_HOURS))
        outputs = load_cdk_outputs(args.cdk_outputs)
        explicit = parse_secret_overrides(args.secret)
        entries: dict[str, object] = {}
        if source in ("generate", "clear"):
            names = [BASIC_AUTH]
        elif source == "file":
            entries = read_file(args.from_file)
            names = list(entries)
        else:
            names = [n for n in WRITABLE if not args.only or n in args.only]
        targets = {name: secret_arn(name, outputs, explicit) for name in names}
        if source == "file":
            values = {name: check_value(name, entries[name]) for name in names}
        elif source == "prompt":
            values = prompt_values(names, prompt)
    except ScriptError as exc:
        return _fail(exc, "read_values", 2)
    script_step(log, "populate_secrets", "read_values", "ok", secrets=sorted(targets), source=source)

    if not args.apply:
        script_step(log, "populate_secrets", "apply", "dry_run")
        print("DRY RUN: no AWS calls; secret values are not shown. Pass --apply to write.")
        if source == "generate":
            print("If the secret already has an active previous password, this rotation would drop it. "
                  + SECOND_ROTATION_WARNING)
        for name, arn in targets.items():
            if source == "generate":
                what = (f"new password ({BASIC_PASSWORD_RULES['PasswordLength']} lower-case hex chars from "
                        f"GetRandomPassword), user kept, old password kept as previous for "
                        f"{overlap_hours:g} h from the write")
            elif source == "clear":
                what = "previous password and its deadline removed, user and password kept"
            else:
                what = describe_lengths(values[name])
            print(f"  {name}: {arn} <- {what}")
        return 0

    if sm_client is None or kms_client is None:
        import boto3

        # The SSO profile may have no default Region, and boto3 ignores AWS_REGION: pick one here.
        try:
            region = resolve_region(args.region, arns=targets.values(), logger=log)
        except ScriptError as exc:
            return _fail(exc, "region", 2)
        sm_client = sm_client or boto3.client("secretsmanager", region_name=region)
        kms_client = kms_client or boto3.client("kms", region_name=region)
    try:
        for arn in targets.values():
            check_kms(arn, sm_client, kms_client)
    except ScriptError as exc:
        return _fail(exc, "check_kms", 3)
    script_step(log, "populate_secrets", "check_kms", "ok")

    basic_values: dict[str, dict[str, Any]] = {}
    dropped_active = False
    if source == "generate":
        try:
            current = _read_basic(targets[BASIC_AUTH], sm_client)
            now = clock()
            dropped_active = has_active_previous(current, now)
            if dropped_active:  # before anything is written
                print(SECOND_ROTATION_WARNING)
            basic_values = {BASIC_AUTH: new_basic_auth(targets[BASIC_AUTH], sm_client, now=now,
                                                      overlap_hours=overlap_hours, current=current)}
        except ScriptError as exc:
            return _fail(exc, "generate_password", 1)
        script_step(log, "populate_secrets", "generate_password", "ok", secret_name=BASIC_AUTH)
    elif source == "clear":
        try:
            basic_values = {BASIC_AUTH: cleared_basic_auth(targets[BASIC_AUTH], sm_client)}
        except ScriptError as exc:
            return _fail(exc, "clear_previous", 1)
        script_step(log, "populate_secrets", "clear_previous", "ok", secret_name=BASIC_AUTH)

    failed = 0
    for name, arn in targets.items():
        try:
            to_write = basic_values[name] if name in basic_values else values[name]
            resp = sm_client.put_secret_value(SecretId=arn, SecretString=json.dumps(to_write))
        except Exception as exc:
            failed += 1
            script_step(log, "populate_secrets", "put_secret", "error", secret_name=name)
            script_error(log, "populate_secrets", exc, step="put_secret", secret_name=name,
                         decision="continue_with_next_secret")
            print(f"  {name}: put_secret_value failed: {_error_code(exc)}", file=sys.stderr)
            continue
        log.info("secret populated", extra={"secret_name": name, "secret_arn": arn})
        script_step(log, "populate_secrets", "put_secret", "changed", secret_name=name)
        print(f"  {name}: {arn} updated (version {resp.get('VersionId', '?')}; {describe_value(to_write)})")
    if source == "generate" and not failed:
        print("\n".join(rotation_steps(basic_values[BASIC_AUTH], dropped_active=dropped_active)))
    elif source == "clear" and not failed:
        print(f"  the previous password may stay accepted for up to {BASIC_CACHE_WAIT_S} s (the secret "
              "cache lifetime)")
    return 1 if failed else 0


if __name__ == "__main__":
    start_logging("populate_secrets")
    sys.exit(main())
