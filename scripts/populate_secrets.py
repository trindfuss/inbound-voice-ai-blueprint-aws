"""Optional helper: write the Twilio secrets, or a fresh Basic password, to Secrets Manager.

CDK creates the three secrets (``infra/owlbank_infra/data_stack.py``). The two Twilio values are
the one manual step after the Data stack is deployed; this helper does it with a shape check first,
instead of typing JSON into the console. The console, the CLI or a bank's own pipeline work as well.

Usage::

    # dry run (the default): hidden prompts, validates, prints secret names and value lengths only
    uv run python scripts/populate_secrets.py --cdk-outputs cdk-outputs.json

    # write the values (put_secret_value), after checking each secret's KMS key
    uv run python scripts/populate_secrets.py --cdk-outputs cdk-outputs.json --apply

    # the values from a JSON file instead of prompts (the file must be chmod 600)
    uv run python scripts/populate_secrets.py --cdk-outputs cdk-outputs.json --from-file twilio.json --apply

    # a new webhook Basic password, generated by Secrets Manager (the user is kept); the old
    # password stays accepted for --overlap-hours (default 8) as the previous password
    uv run python scripts/populate_secrets.py --cdk-outputs cdk-outputs.json --new-basic-password --apply

    # end the overlap early: drop the previous password
    uv run python scripts/populate_secrets.py --cdk-outputs cdk-outputs.json --clear-previous-basic-password --apply

Values (JSON objects, read by ``owlbank.secrets``; shapes in ``owlbank.secret_schema``):

=====================  =====================================================
Secret                 Secret JSON
=====================  =====================================================
``twilio_api_key``     ``{"account_sid", "api_key", "api_secret"}``
``twilio_auth_token``  ``{"auth_token"}``
``basic_auth``         ``{"user", "password"}`` and, during a rotation overlap,
                       ``{"previous_password", "previous_until"}`` (epoch seconds):
                       only via ``--new-basic-password`` / ``--clear-previous-basic-password``
=====================  =====================================================

Sources:

* **Prompts** (the default): one hidden prompt (``getpass``) per field of each Twilio secret, or of
  the ones named with ``--only``.
* ``--from-file PATH``: ``{"twilio_api_key": {...}, "twilio_auth_token": {...}}``. A missing entry
  is skipped; any other entry is refused. The file is refused if group or others may read it.
* ``--new-basic-password``: ``secretsmanager:GetRandomPassword`` with the CDK generator's rules
  (48 lower-case hex characters); writes only ``basic_auth``, keeping its current ``user``
  (the old password isn't checked, so a malformed one doesn't block it; it just isn't kept).
  The old password is stored as ``previous_password`` with ``previous_until`` (now + ``--overlap-hours``,
  default 8). A second rotation inside an overlap sets the previous password to the then-current one,
  so at most two passwords are ever stored. The command prints the deadline and the steps: wait about
  60 s (the secret cache), then re-run ``twilio_setup.py --phase post --apply`` before the deadline.
* ``--clear-previous-basic-password``: removes ``previous_password`` and ``previous_until``; the previous
  password may stay accepted for up to 60 s (one cache lifetime) after the write.

Secret ARNs come from ``--secret NAME=ARN`` or the CDK outputs file (``SecretTwilioApiKey`` and so
on, :data:`scripts._common.SECRET_OUTPUTS`). Region: ``--region``, else the Region in the secrets'
ARNs, else ``AWS_DEFAULT_REGION`` or ``AWS_REGION``, else ``us-east-1``.

Guarantees:

* **Values are never printed or logged**, in either mode, and never appear in error messages.
  Only names, ARNs, field names and lengths are shown.
* Every value is checked with :func:`owlbank.secret_schema.validate` before anything is written.
* The dry run (the default) makes no AWS call.
* ``--apply`` first checks *every* selected secret with ``describe_secret`` and ``kms:DescribeKey``:
  it refuses to write anything if a secret isn't encrypted with a customer-managed KMS key.

Exit codes: 0 done (or dry run), 1 a write or read failed, 2 a usage or input error (nothing
written, no AWS call), 3 a secret without a customer-managed key (nothing written).
"""

