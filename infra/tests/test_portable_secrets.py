"""Portable secrets.

- ``basic_auth`` is generated by Secrets Manager: ``{"user": <basicAuthUser>, "password":
  48 lower-case hex}``, never a literal value in the template. The two Twilio secrets keep the
  placeholder until the operator sets them.
- No template has a secret-named parameter.
- Synth refuses any context key that isn't in ``app_builder.CONTEXT_KEYS``, skipping CDK's own
  namespaces.
"""

from __future__ import annotations

import json
import re
import string
from pathlib import Path

import pytest
from conftest import _synth
from hypothesis import given, settings
from hypothesis import strategies as st

from owlbank_infra import app_builder
from owlbank_infra.app_builder import CONTEXT_KEYS, build_app
from owlbank_infra.config import (
    BASIC_AUTH_USER_RE,
    DEFAULT_BASIC_AUTH_USER,
    ConfigError,
    check_context_keys,
    from_context,
)
from owlbank_infra.data_stack import BASIC_AUTH_EXCLUDE_CHARACTERS, BASIC_AUTH_PASSWORD_LENGTH

INFRA = Path(__file__).resolve().parents[1]
BASE = INFRA
DATA = "OwlBankData"
SECRET_WORDS = ("token", "secret", "password", "apikey", "api_key", "authtoken")
#: A ``password`` value: 32 or more lower-case hex digits.
PASSWORD_RE = re.compile(r"[0-9a-f]{32,}")


def _secret(synth, logical_prefix: str) -> dict:
    found = [res for lid, res in synth.templates[DATA]["Resources"].items()
             if res["Type"] == "AWS::SecretsManager::Secret" and lid.startswith(logical_prefix)]
    assert len(found) == 1, logical_prefix
    return found[0]["Properties"]


# --- The generated Basic auth secret ----------------------------------------------------

def test_basic_auth_has_the_generator(synth_default) -> None:
    props = _secret(synth_default, "BasicAuthSecret")
    assert props["GenerateSecretString"] == {
        "SecretStringTemplate": json.dumps({"user": DEFAULT_BASIC_AUTH_USER}),
        "GenerateStringKey": "password",
        "PasswordLength": 48,
        "ExcludePunctuation": True,
        "ExcludeUppercase": True,
        "IncludeSpace": False,
        "ExcludeCharacters": "ghijklmnopqrstuvwxyz",
    }
    assert "SecretString" not in props
    assert "password" not in json.loads(props["GenerateSecretString"]["SecretStringTemplate"])
    assert "Generated by Secrets Manager" in props["Description"]


@pytest.mark.parametrize("prefix", ["TwilioApiKeySecret", "TwilioAuthTokenSecret"])
def test_twilio_secrets_keep_the_placeholder(synth_default, prefix) -> None:
    props = _secret(synth_default, prefix)
    assert props["GenerateSecretString"] == {"SecretStringTemplate": '{"placeholder": true}',
                                             "GenerateStringKey": "unset", "ExcludePunctuation": True}
    assert "SecretString" not in props
    assert "populate_secrets.py" in props["Description"] and "Keychain" not in props["Description"]


def test_no_secret_has_a_literal_value(synth_default) -> None:
    for _, lid, res in synth_default.resources("AWS::SecretsManager::Secret"):
        assert "SecretString" not in res["Properties"], lid


@pytest.mark.parametrize("fixture", ["synth_default", "synth_domain", "synth_prod"])
def test_no_template_has_a_secret_named_parameter(fixture, request) -> None:
    for stack, tpl in request.getfixturevalue(fixture).templates.items():
        for name in tpl.get("Parameters", {}):
            assert not any(w in name.lower() for w in SECRET_WORDS), (stack, name)


def test_basic_auth_user_reaches_the_template(tmp_path_factory) -> None:
    synth = _synth(tmp_path_factory, "basic-user", {"basicAuthUser": "twilio.hooks-1"})
    template = _secret(synth, "BasicAuthSecret")["GenerateSecretString"]["SecretStringTemplate"]
    assert json.loads(template) == {"user": "twilio.hooks-1"}


