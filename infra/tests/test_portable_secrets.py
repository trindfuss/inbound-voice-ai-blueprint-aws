# --- The generation rules allow only lower-case hex ------------------------------------------

#: Secrets Manager draws from ASCII letters, digits and these punctuation characters.
SM_PUNCTUATION = "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~"
PD2_ALPHABET = "".join(sorted(set(string.ascii_lowercase + string.digits)
                              - set(BASIC_AUTH_EXCLUDE_CHARACTERS)))


def test_the_alphabet_is_lower_case_hex() -> None:
    allowed = set(string.ascii_letters + string.digits + SM_PUNCTUATION + " ")
    allowed -= set(SM_PUNCTUATION) | set(string.ascii_uppercase) | {" "}
    allowed -= set(BASIC_AUTH_EXCLUDE_CHARACTERS)
    assert "".join(sorted(allowed)) == PD2_ALPHABET == "0123456789abcdef"
    assert BASIC_AUTH_PASSWORD_LENGTH >= 32


@settings(max_examples=300)
@given(st.text(alphabet=PD2_ALPHABET, min_size=BASIC_AUTH_PASSWORD_LENGTH,
               max_size=BASIC_AUTH_PASSWORD_LENGTH))
def test_every_password_is_lower_case_hex(password) -> None:
    assert PASSWORD_RE.fullmatch(password)


# --- The context allow-list -------------------------------------------------------------

_KEY = st.text(alphabet=string.ascii_letters + string.digits + "_-./", min_size=1, max_size=40)
#: Keys outside CDK's namespaces that aren't listed.
UNKNOWN_KEY = _KEY.filter(lambda k: k not in CONTEXT_KEYS and not k.startswith(("aws", "@")))
#: CDK's own keys: ``aws:*``, ``@aws-cdk/*`` and cached lookups (any key with a ``:``).
CDK_KEY = st.one_of(_KEY.map(lambda k: "aws:" + k), _KEY.map(lambda k: "@aws-cdk/" + k),
                    st.tuples(_KEY, _KEY).map(lambda t: f"{t[0]}:{t[1]}"))


def _cdk_json_keys() -> list[str]:
    return list(json.loads((INFRA / "cdk.json").read_text())["context"])


def _config_read_keys() -> set[str]:
    """Every context key ``config.py`` reads, by a source scan (``ctx.get("k")``, ``_str(ctx, "k")``...)."""
    src = (INFRA / "owlbank_infra" / "config.py").read_text()
    return set(re.findall(r'ctx(?:\.get\(|\[|, )"([A-Za-z]+)"', src))


def test_every_key_the_blueprint_uses_is_known() -> None:
    real = set(_cdk_json_keys()) | _config_read_keys()
    assert real, "the scan found nothing"
    assert real <= set(CONTEXT_KEYS), sorted(real - set(CONTEXT_KEYS))
    check_context_keys(list(real) + list(CONTEXT_KEYS), CONTEXT_KEYS)
    assert "basicAuthUser" in CONTEXT_KEYS
    assert len(set(CONTEXT_KEYS)) == len(CONTEXT_KEYS)


@settings(max_examples=300)
@given(st.lists(st.sampled_from(CONTEXT_KEYS), unique=True), st.lists(CDK_KEY, max_size=5),
       st.lists(UNKNOWN_KEY, min_size=1, max_size=3, unique=True))
def test_any_unknown_key_fails_naming_it(known, cdk, unknown) -> None:
    with pytest.raises(ConfigError) as err:
        check_context_keys(known + cdk + unknown, CONTEXT_KEYS)
    for key in unknown:
        assert repr(key) in str(err.value)
    for key in known + cdk:
        assert repr(key) not in str(err.value)
    assert "infra/README.md" in str(err.value) and "First deploy" in str(err.value)


@settings(max_examples=300)
@given(st.lists(st.sampled_from(CONTEXT_KEYS), unique=True), st.lists(CDK_KEY, max_size=8))
def test_known_and_cdk_keys_pass(known, cdk) -> None:
    check_context_keys(known + cdk, CONTEXT_KEYS)


