def check_access_analyzer(analyzer: Any, analyzer_name: str, own_ids: set[str] | None = None, *,
                          strict: bool = False, unscoped_reason: str | None = None) -> Result:
    """Fail only for ACTIVE findings on the blueprint's own resources (``own_ids``); other findings
    are a count in a WARN note. ``strict`` (``--strict-account``) fails on any finding. With no
    ``own_ids`` (the stack resources couldn't be listed, ``unscoped_reason``) the count is reported
    unfiltered, with the reason, and any finding fails."""
    name = f"IAM Access Analyzer {analyzer_name}"
    arns = [a["arn"] for page in analyzer.get_paginator("list_analyzers").paginate(type="ACCOUNT")
            for a in page["analyzers"] if a["name"] == analyzer_name]
    if not arns:
        return Result(name, False, "analyzer not found (is the Data stack deployed?)",
                      "deploy OwlBankData, then rerun with --post-deploy")
    findings = [f for page in analyzer.get_paginator("list_findings").paginate(
        analyzerArn=arns[0], filter={"status": {"eq": ["ACTIVE"]}}) for f in page["findings"]]
    if not findings:
        return Result(name, True, "no ACTIVE findings")

    def listing(items: list[dict[str, Any]]) -> str:
        return "; ".join(f"{f.get('resourceType')} {f.get('resource')}" for f in items[:10])

    fix = (f"aws accessanalyzer list-findings --analyzer-arn {arns[0]} "
           "--filter '{\"status\":{\"eq\":[\"ACTIVE\"]}}'  (review, then remove the sharing)")
    if own_ids is None:
        return Result(name, False, f"{len(findings)} ACTIVE finding(s), unfiltered because the stack "
                      f"resources couldn't be listed ({unscoped_reason or 'unknown reason'}): "
                      f"{listing(findings)}", fix)
    own, other = split_findings(findings, own_ids)
    if strict:
        return Result(name, False, f"{len(findings)} ACTIVE finding(s) in the account "
                      f"(--strict-account): {listing(findings)}", fix)
    if own:
        note = f"; {len(other)} more on other resources in the account (not ours)" if other else ""
        return Result(name, False, f"{len(own)} ACTIVE finding(s) on this blueprint's resources: "
                      f"{listing(own)}{note}", fix)
    return Result(name, True, f"no ACTIVE findings on this blueprint's resources; {len(other)} on other "
                  "resources in the account (not ours, so not a failure; --strict-account fails on them)",
                  fix, warn=True)


