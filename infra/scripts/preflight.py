def check_invocation_logging(bedrock_for_region: Callable[[str], Any], ceiling: str,
                             regions: tuple[str, ...], *,
                             accept_text_logging: bool = False) -> list[Result]:
    """One result per Region: PASS if there is no ``loggingConfig`` or
    ``textDataDeliveryEnabled`` is ``false``; anything else (on, or not set to false, or the read
    fails) FAILs, or WARNs when ``ceiling`` is ``deterministic`` (the resolver is then never called)
    or when ``accept_text_logging`` is set (dev or test only: the caller refuses it at stage prod;
    the owner accepts that test speech is logged in a trusted sandbox).
    ``bedrock_for_region`` returns a Bedrock client for a Region. Names fields only: the destinations'
    bucket and log group names are never read into a message."""
    if not regions:
        return [Result("Bedrock invocation logging", False, "no Region to check",
                       "pass the deployment Region (--region) and --logging-regions")]
    deterministic = ceiling == "deterministic"
    out = []
    for region in regions:
        name = f"Bedrock invocation logging ({region})"

        def result(detail: str, fix: str, name: str = name) -> Result:
            if deterministic:
                return Result(name, True, detail + "; slotModeCeiling is deterministic, so the resolver "
                              "is never called: WARN, not FAIL (it FAILs once the ceiling is raised)",
                              fix, warn=True)
            if accept_text_logging:
                return Result(name, True, detail + "; accepted with --accept-text-logging (dev/test "
                              "only): WARN, not FAIL. Treat everything callers say as logged", fix,
                              warn=True)
            return Result(name, False, detail, fix)

        client = bedrock_for_region(region)
        if client is None:
            out.append(result(f"no Bedrock client for {region}, so the configuration can't be read",
                              f"rerun with a profile that can call Bedrock in {region}"))
            continue
        try:
            conf = client.get_model_invocation_logging_configuration().get("loggingConfig")
        except Exception as exc:
            code = _error_code(exc)
            out.append(result(f"GetModelInvocationLoggingConfiguration in {region} failed ({code}), so "
                              "invocation logging can't be confirmed off",
                              "use a role allowed bedrock:GetModelInvocationLoggingConfiguration in "
                              f"{region}, then rerun preflight"))
            continue
        if conf is None:
            out.append(Result(name, True, f"no invocation logging configuration in {region}"))
            continue
        if conf.get("textDataDeliveryEnabled") is False:
            out.append(Result(name, True, f"invocation logging is configured in {region} but "
                              "textDataDeliveryEnabled is false"))
            continue
        state = "true" if conf.get("textDataDeliveryEnabled") is True else "not set to false"
        dests = [k for k in ("s3Config", "cloudWatchConfig") if k in conf]
        out.append(result(
            f"Bedrock model invocation logging is on in {region} with loggingConfig.textDataDeliveryEnabled "
            f"{state} (destinations: {', '.join(dests) or 'none named'}). Every resolver prompt would then "
            "be written to the log with callers' digits (ZIP, SSN last four, codes) in it",
            LOGGING_FIX))
    return out


def _field_selector_matches(fs: dict[str, Any], event: dict[str, str]) -> bool:
    """One advanced field selector against ``event``. A field the event doesn't model never matches
    (fail closed); within a field selector every operator must hold, any value of one operator may."""
    value = event.get(fs.get("Field", ""))
    if value is None:
        return False
    checks = {"Equals": lambda vs: value in vs, "NotEquals": lambda vs: value not in vs,
              "StartsWith": lambda vs: any(value.startswith(v) for v in vs),
              "NotStartsWith": lambda vs: not any(value.startswith(v) for v in vs),
              "EndsWith": lambda vs: any(value.endswith(v) for v in vs),
              "NotEndsWith": lambda vs: not any(value.endswith(v) for v in vs)}
    return all(check(fs[op]) for op, check in checks.items() if op in fs)


def records_logging_write(selectors: dict[str, Any], event: dict[str, str] = LOGGING_WRITE_EVENT) -> bool:
    """Whether ``GetEventSelectors``' answer records ``event`` (a management write).

    Basic selectors: ``IncludeManagementEvents`` (default true), ``ReadWriteType`` ``All`` or
    ``WriteOnly`` (default ``All``) and the event source not in ``ExcludeManagementEventSources``.
    Advanced: a selector that names ``eventCategory`` and whose every field selector matches."""
    for sel in selectors.get("EventSelectors") or []:
        if (sel.get("IncludeManagementEvents", True) is True
                and sel.get("ReadWriteType", "All") in ("All", "WriteOnly")
                and event["eventSource"] not in (sel.get("ExcludeManagementEventSources") or [])):
            return True
    for sel in selectors.get("AdvancedEventSelectors") or []:
        fields = sel.get("FieldSelectors") or []
        if (any(f.get("Field") == "eventCategory" for f in fields)
                and all(_field_selector_matches(f, event) for f in fields)):
            return True
    return False


def check_management_trail(cloudtrail: Any, region: str, stage: str) -> Result:
    """PASS when a trail that applies to ``region`` (multi-Region, or homed here) is logging and
    records management write events; otherwise WARN in dev and test, FAIL at
    ``stage=prod``. A trail whose status or selectors can't be read doesn't count. Never names a
    trail's bucket or log group."""
    name = f"CloudTrail management write events ({region})"
    why = (f"No CloudTrail trail is logging management write events in {region}. Without one, "
           "EventBridge never receives PutModelInvocationLoggingConfiguration, so the alarm on Bedrock "
           "invocation logging can't fire")
    fix = ("create or enable a trail that logs management write events in this Region (aws cloudtrail "
           "create-trail --name <name> --s3-bucket-name <your trail bucket> --is-multi-region-trail "
           f"--region {region}, then aws cloudtrail start-logging --name <name> --region {region}), or "
           "confirm your organization trail covers this account, then rerun preflight")

    def missing(reasons: str, fix: str = fix) -> Result:
        detail = f"{why} ({reasons})"
        if stage == "prod":
            return Result(name, False, detail, fix)
        return Result(name, True, detail + f"; WARN in {stage}, FAIL at stage prod", fix, warn=True)

    try:
        trails = cloudtrail.describe_trails(includeShadowTrails=True).get("trailList", [])
    except Exception as exc:
        return missing(f"DescribeTrails failed ({_error_code(exc)}), so no trail could be confirmed",
                       "use a role allowed cloudtrail:DescribeTrails, cloudtrail:GetTrailStatus and "
                       "cloudtrail:GetEventSelectors, then rerun preflight")
    counts: dict[str, int] = {}

    def note(reason: str) -> None:
        counts[reason] = counts.get(reason, 0) + 1

    for trail in trails:
        if not (trail.get("IsMultiRegionTrail") or trail.get("HomeRegion") == region):
            note("in another Region")
            continue
        ident = trail.get("TrailARN") or trail.get("Name")
        try:
            logging = cloudtrail.get_trail_status(Name=ident).get("IsLogging") is True
        except Exception as exc:
            note(f"unreadable ({_error_code(exc)})")
            continue
        if not logging:
            note("not logging")
            continue
        try:
            selectors = cloudtrail.get_event_selectors(TrailName=ident)
        except Exception as exc:
            note(f"unreadable ({_error_code(exc)})")
            continue
        if records_logging_write(selectors):
            return Result(name, True, f"a logging trail records management write events in {region}")
        note("not recording management write events")
    found = f"{len(trails)} trail(s) found"
    if counts:
        found += ": " + ", ".join(f"{n} {reason}" for reason, n in sorted(counts.items()))
    return missing(found)


def transaction_search_policy(region: str, account: str) -> dict[str, Any]:
    """The resource policy X-Ray needs to write spans to CloudWatch Logs (``aws/spans`` and
    Application Signals' group), with confused-deputy conditions. ``PutLogEvents`` only: the stack
    creates its own ``spans`` stream."""
    return {"Version": "2012-10-17", "Statement": [{
        "Sid": "TransactionSearchXRayAccess", "Effect": "Allow",
        "Principal": {"Service": "xray.amazonaws.com"}, "Action": "logs:PutLogEvents",
        "Resource": [f"arn:aws:logs:{region}:{account}:log-group:aws/spans:*",
                     f"arn:aws:logs:{region}:{account}:log-group:/aws/application-signals/data:*"],
        "Condition": {"ArnLike": {"aws:SourceArn": f"arn:aws:xray:{region}:{account}:*"},
                      "StringEquals": {"aws:SourceAccount": account}}}]}


def transaction_search_fix(region: str, account: str) -> str:
    """The two commands that enable Transaction Search, in the order to run them."""
    doc = json.dumps(transaction_search_policy(region, account), separators=(",", ":"))
    return (f"aws logs put-resource-policy --region {region} --policy-name TransactionSearchXRayAccess "
            f"--policy-document '{doc}' && "
            f"aws xray update-trace-segment-destination --region {region} --destination CloudWatchLogs")


def _as_list(value: Any) -> list[Any]:
    return value if isinstance(value, list) else [value]


def _allows_xray_spans(document: str, target: str) -> bool:
    """Whether a resource policy document has an Allow statement for principal service
    ``xray.amazonaws.com`` with ``logs:PutLogEvents`` on ``target`` (wildcards honoured)."""
    try:
        statements = _as_list(json.loads(document).get("Statement", []))
    except (ValueError, AttributeError):
        return False
    for st in statements:
        if not isinstance(st, dict) or st.get("Effect") != "Allow":
            continue
        principal = st.get("Principal")
        services = _as_list(principal.get("Service", [])) if isinstance(principal, dict) else []
        if "xray.amazonaws.com" not in services:
            continue
        if not any(fnmatchcase("logs:PutLogEvents", a) for a in _as_list(st.get("Action", []))
                   if isinstance(a, str)):
            continue
        if any(fnmatchcase(target, r) for r in _as_list(st.get("Resource", [])) if isinstance(r, str)):
            return True
    return False


def check_transaction_search(xray: Any, logs: Any, region: str, account: str) -> Result:
    """With ``callObservability=on`` X-Ray must deliver spans to
    CloudWatch Logs (Transaction Search). PASS when the trace segment destination is
    ``CloudWatchLogs``/``ACTIVE`` and a CloudWatch Logs resource policy lets ``xray.amazonaws.com``
    ``logs:PutLogEvents`` into ``aws/spans``; WARN while the destination is ``PENDING``; FAIL, with
    the two commands, when it is off or the policy is missing; FAIL closed when either can't be read.
    Preflight never enables it: it is account-wide (every X-Ray trace in the Region)."""
    name = f"X-Ray Transaction Search ({region})"
    scope = (f"Transaction Search is account-wide: enabling it sends every X-Ray trace in {region} "
             "to CloudWatch Logs (aws/spans), not just this stack's")
    fix = transaction_search_fix(region, account)
    unreadable_fix = ("use a role allowed xray:GetTraceSegmentDestination and "
                      "logs:DescribeResourcePolicies, then rerun preflight")
    try:
        dest = xray.get_trace_segment_destination()
    except Exception as exc:
        return Result(name, False, f"GetTraceSegmentDestination failed ({_error_code(exc)}), so "
                      f"Transaction Search can't be confirmed on. {scope}", unreadable_fix)
    target = f"arn:aws:logs:{region}:{account}:log-group:aws/spans:*"
    policies: list[dict[str, Any]] = []
    try:
        token = None
        while True:
            page = logs.describe_resource_policies(**({"nextToken": token} if token else {}))
            policies += page.get("resourcePolicies", [])
            token = page.get("nextToken")
            if not token:
                break
    except Exception as exc:
        return Result(name, False, f"DescribeResourcePolicies failed ({_error_code(exc)}), so X-Ray's "
                      f"access to aws/spans can't be confirmed. {scope}", unreadable_fix)
    has_policy = any(_allows_xray_spans(p.get("policyDocument", ""), target) for p in policies)
    destination, status = dest.get("Destination"), dest.get("Status")
    problems = []
    if destination != "CloudWatchLogs":
        problems.append(f"the trace segment destination is {destination or 'not set'} "
                        "(Transaction Search is off)")
    if not has_policy:
        problems.append("no CloudWatch Logs resource policy lets xray.amazonaws.com logs:PutLogEvents "
                        "into aws/spans")
    if problems:
        return Result(name, False, "; ".join(problems) + f". callObservability=on needs it. {scope}. "
                      "Run the commands yourself, or deploy with tracesEnableTransactionSearch=true in a "
                      "dedicated account", fix)
    if status == "PENDING":
        return Result(name, True, "the destination is CloudWatchLogs but still PENDING; it activates "
                      f"within minutes. {scope}", "rerun preflight in a few minutes to confirm ACTIVE", warn=True)
    if status != "ACTIVE":
        return Result(name, False, f"the destination is CloudWatchLogs but its status is {status}. "
                      f"{scope}", fix)
    return Result(name, True, f"destination CloudWatchLogs ACTIVE and X-Ray may write to aws/spans. {scope}")


def arn_matches(arn: str, physical_id: str) -> bool:
    """``arn`` names the resource ``physical_id``: equal, or ending in ``/<id>`` or ``:<id>``."""
    return bool(physical_id) and (arn == physical_id or arn.endswith(("/" + physical_id, ":" + physical_id)))


def split_findings(findings: list[dict[str, Any]], own_ids: set[str]) -> tuple[list[dict[str, Any]],
                                                                               list[dict[str, Any]]]:
    """``(own, other)``: a finding is ours when its resource matches one of ``own_ids``. Every finding
    lands in exactly one list."""
    own: list[dict[str, Any]] = []
    other: list[dict[str, Any]] = []
    for f in findings:
        resource = str(f.get("resource") or "")
        (own if any(arn_matches(resource, i) for i in own_ids) else other).append(f)
    return own, other


