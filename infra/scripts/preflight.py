def check_secrets_populated(secrets: Any, names: tuple[str, ...] = TWILIO_SECRETS) -> list[Result]:
    """Present and, for an operator-written secret, written. A secret that CDK created has one
    version; ``populate_secrets.py`` (or any ``put-secret-value``) adds a second, so the first becomes
    ``AWSPREVIOUS``. A generated secret (:data:`GENERATED_SECRETS`) passes with an ``AWSCURRENT``
    version. Reads metadata only, never a value."""
    out = []
    for secret in names:
        generated = secret in GENERATED_SECRETS
        label = f"Secret {secret} {'present' if generated else 'populated'}"
        try:
            desc = secrets.describe_secret(SecretId=secret)
        except secrets.exceptions.ResourceNotFoundException:
            out.append(Result(label, False, "secret not found (is OwlBankData deployed?)",
                              "cdk deploy OwlBankData" + ("" if generated else ", then populate_secrets.py")))
            continue
        if desc.get("DeletedDate"):
            out.append(Result(label, False, "scheduled for deletion",
                              f"aws secretsmanager restore-secret --secret-id {secret}"))
            continue
        stages = [st for sts in desc.get("VersionIdsToStages", {}).values() for st in sts]
        if generated:
            ok = "AWSCURRENT" in stages
            out.append(Result(label, ok, "generated by Secrets Manager; it has a current version" if ok
                              else "no current version", "" if ok else "cdk deploy OwlBankData"))
            continue
        ok = "AWSPREVIOUS" in stages
        out.append(Result(label, ok, "a value has been written" if ok else "still the generated placeholder",
                          "" if ok else "uv run python scripts/populate_secrets.py --cdk-outputs "
                                        "infra/cdk-outputs.json --apply  (dry run first; or put-secret-value, "
                                        "see infra/README.md)"))
    return out


