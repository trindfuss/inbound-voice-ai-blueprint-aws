@dataclass
class Result:
    name: str
    ok: bool
    detail: str
    fix: str = ""
    #: A PASS worth reading: printed as WARN with its fix, never fails the run.
    warn: bool = False
    #: A FAIL that can clear after the first invocation of the model (model access, 8.4).
    clearable: bool = False


def check_s3_public_access_block(s3control: Any, account_id: str) -> Result:
    name = "S3 Block Public Access (account)"
    fix = (f"aws s3control put-public-access-block --account-id {account_id} "
           "--public-access-block-configuration "
           "BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true")
    try:
        conf = s3control.get_public_access_block(AccountId=account_id)["PublicAccessBlockConfiguration"]
    except s3control.exceptions.NoSuchPublicAccessBlockConfiguration:
        return Result(name, False, "no account-level configuration (all four are off)", fix)
    off = [k for k in BPA_KEYS if conf.get(k) is not True]
    if off:
        return Result(name, False, "off: " + ", ".join(off), fix)
    return Result(name, True, "all four settings on")


def _region_of(arn: str) -> str:
    return arn.split(":")[3]


def check_inference_profile(bedrock: Any, profile_id: str) -> list[Result]:
    name = f"Bedrock inference profile {profile_id}"
    geo = profile_id.split(".", 1)[0]
    allowed = GEO_REGIONS.get(geo)
    if allowed is None:
        return [Result(name, False, f"not a geo inference profile ({geo!r})",
                       "use a geo profile (us./eu./apac.) as modelId")]
    prof = bedrock.get_inference_profile(inferenceProfileIdentifier=profile_id)
    regions = sorted({_region_of(m["modelArn"]) for m in prof.get("models", [])})
    print(f"  {profile_id} destination Regions: {', '.join(regions) or '(none)'}")
    outside = [r for r in regions if not r.startswith(allowed)]
    out = [Result(name, bool(regions) and not outside,
                  f"destination Regions {regions}" + (f"; outside {geo}: {outside}" if outside else ""),
                  "" if not outside else "use a profile whose Regions stay in the geography")]
    out.append(check_model_access(bedrock, profile_id))
    return out


def check_model_access(bedrock: Any, profile_id: str) -> Result:
    """The model-access line for ``profile_id``'s base model. A failure whose Region is available is
    ``clearable``: access may only show up after the model's first invocation (8.4), so the fix says
    to rerun."""
    base = profile_id.split(".", 1)[1]
    avail = bedrock.get_foundation_model_availability(modelId=base)
    good = (avail.get("authorizationStatus") == "AUTHORIZED"
            and avail.get("entitlementAvailability") == "AVAILABLE"
            and avail.get("regionAvailability") == "AVAILABLE"
            and avail.get("agreementAvailability", {}).get("status") in ("AVAILABLE", None))
    return Result(
        f"Bedrock model access {base}", good,
        "authorization={authorizationStatus} entitlement={entitlementAvailability} "
        "region={regionAvailability} agreement={a}".format(
            a=avail.get("agreementAvailability", {}).get("status"), **{
                k: avail.get(k) for k in ("authorizationStatus", "entitlementAvailability",
                                          "regionAvailability")}),
        "" if good else "request model access in the Bedrock console (Model access) for this Region; "
                        "it may clear after the model's first invocation, so rerun preflight",
        clearable=not good and avail.get("regionAvailability") == "AVAILABLE")


def recheck_model_access(first: Result, bedrock: Any, profile_id: str, used_ids: list[str]) -> Result:
    """The model-access result to report once the live invocation has run. ``first`` stands when it
    passed (a rerun never turns a PASS into a FAIL), when it failed with a status that can't clear, when
    the live invocation didn't use ``profile_id``, or when the rerun can't be read; otherwise the
    check is repeated once and the second result is reported."""
    if first.ok or not first.clearable or profile_id not in used_ids:
        return first
    try:
        return check_model_access(bedrock, profile_id)
    except Exception:  # noqa: BLE001 - the first result stands
        return first


def _load_resolver() -> Any:
    """``resolve_models.py``, next to this file (imported by path so the tests, which load this script
    without its directory on ``sys.path``, find it too)."""
    here = str(Path(__file__).resolve().parent)
    if here not in sys.path:
        sys.path.insert(0, here)
    import resolve_models  # noqa: PLC0415

    return resolve_models


def resolve_list(bedrock: Any, runtime: Any, region: str, model_ids: list[str] | None = None,
                 params: dict[str, dict[str, Any]] | None = None, geo: str | None = None,
                 has_prompt: Callable[[str], bool] | None = None) -> Any:
    """``resolve_models.resolve`` (its ``Resolution``); prints the final list and the
    ``-c modelIds=[...]`` to deploy with."""
    res = _load_resolver().resolve(bedrock=bedrock, runtime=runtime, region=region, model_ids=model_ids,
                                   params=params, geo=geo, has_prompt=has_prompt)
    if res.entries:
        print(f"  model list: {', '.join(res.model_ids)}")
        print(f"  deploy with: {res.deploy_args()}")
    return res


def model_results(res: Any) -> list[Result]:
    return [Result(f.name, f.level != "FAIL", f.detail, f.fix, warn=f.level == "WARN")
            for f in res.findings]


def check_models(bedrock: Any, runtime: Any, region: str, model_ids: list[str] | None = None,
                 params: dict[str, dict[str, Any]] | None = None, geo: str | None = None,
                 has_prompt: Callable[[str], bool] | None = None) -> list[Result]:
    """The model list's FAIL/WARN/PASS lines from ``resolve_models``;
    prints the final list and the ``-c modelIds=[...]`` to deploy with."""
    return model_results(resolve_list(bedrock, runtime, region, model_ids, params, geo, has_prompt))


