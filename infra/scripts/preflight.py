class PromptCatalogCopy:
    """The served templates of a seed-file catalog, as ``owlbank.catalog.PromptCatalog`` serves them:
    published entries only, the highest ``version`` per key and language; a missing language falls
    back to the key's single language (``singleLanguageKeys``), then to ``defaultLanguage``."""

    def __init__(self, doc: Mapping[str, Any]) -> None:
        self.default_language = str(doc["defaultLanguage"])
        self.languages = tuple(str(lang) for lang in doc["languages"])
        self.single = {str(k): str(v) for k, v in (doc.get("singleLanguageKeys") or {}).items()}
        best: dict[tuple[str, str], tuple[int, str]] = {}
        #: Every published entry as ``(key, lang, text)``, in file order (the placeholder check reads each).
        self.published: tuple[tuple[str, str, str], ...] = tuple(
            (str(e["key"]), str(e["lang"]), str(e["text"])) for e in doc.get("entries", [])
            if e.get("status", "published") == "published")
        for e in doc.get("entries", []):
            if e.get("status", "published") != "published":
                continue
            key, version = (str(e["key"]), str(e["lang"])), int(e.get("version", 0))
            if key not in best or version > best[key][0]:
                best[key] = (version, str(e["text"]))
        self.texts = {k: text for k, (_, text) in best.items()}

    def template(self, key: str, lang: str) -> str | None:
        """The served template, or ``None`` (``CatalogKeyError`` in the bridge)."""
        for candidate in (lang, self.single.get(key), self.default_language):
            if candidate is not None and (key, candidate) in self.texts:
                return self.texts[(key, candidate)]
        return None


def allowed_placeholders(key: str) -> frozenset[str] | None:
    """``owlbank.agent_prompt.allowed_placeholders``: the exact set an ``agent.*`` text must
    have; ``None`` for a key outside ``agent.``."""
    if not key.startswith(AGENT_PREFIX):
        return None
    return ALLOWED_PLACEHOLDERS.get(key, frozenset())


def placeholder_problems(key: str, text: str) -> str | None:
    """``owlbank.agent_prompt.placeholder_problems``: why ``text`` breaks the allow-list for
    ``key`` (a stray brace or the wrong set), else ``None``."""
    allowed = allowed_placeholders(key)
    if allowed is None:
        return None
    rest = PLACEHOLDER.sub("", text)
    if "{" in rest or "}" in rest:
        return "has a '{' or '}' that isn't a {placeholder}"
    if frozenset(PLACEHOLDER.findall(text)) != allowed:
        if not allowed:
            return "must have no placeholders"
        return "must have exactly " + ", ".join(f"{{{n}}}" for n in sorted(allowed))
    return None


def agent_text_problems(catalog: PromptCatalogCopy) -> list[str]:
    """``scripts/seed.py``'s ``agent_text_problems``: each published ``agent.*`` entry that breaks
    the placeholder allow-list (``"key (lang): why"``, in file order), then each caller-context frame with no published
    entry in a catalog language (``"key (lang): missing"``)."""
    out = [f"{key} ({lang}): {why}" for key, lang, text in catalog.published
           for why in [placeholder_problems(key, text)] if why is not None]
    present = {(key, lang) for key, lang, _ in catalog.published}
    return out + [f"{key} ({lang}): missing" for lang in catalog.languages
                  for key in (CALLER_CONTEXT_KEY, CALLER_CONTEXT_UNVERIFIED_KEY) if (key, lang) not in present]


def prompt_parts(catalog: PromptCatalogCopy, model_key: str, lang: str) -> list[str | None] | None:
    """``owlbank.agent_prompt.prompt_parts`` as a list in field order (model text, both web-activity
    blocks, placeholder rule, language-line template, both caller-context frames, then the unknown
    name, empty value and fallback per-call part), or ``None`` when the model's text is missing."""
    text = catalog.template(f"{SYSTEM_KEY_PREFIX}.{model_key}", lang)
    if text is None:
        return None

    def per_lang(table: Mapping[str, str]) -> str:
        return table.get(lang) or table[DEFAULT_PLACEHOLDER_LANG]

    return [text, catalog.template(WEB_ACTIVITY_KEY, lang), catalog.template(WEB_ACTIVITY_CONTEXT_KEY, lang),
            per_lang(PLACEHOLDER_SENTENCE), CALL_LANGUAGE_LINE,
            catalog.template(CALLER_CONTEXT_KEY, lang), catalog.template(CALLER_CONTEXT_UNVERIFIED_KEY, lang),
            per_lang(UNKNOWN_NAME), per_lang(EMPTY_VALUE), per_lang(FALLBACK_CONTEXT)]


def prompt_hash(catalog: PromptCatalogCopy, model_key: str, lang: str) -> str | None:
    """``owlbank.agent_prompt.prompt_hash``: SHA-256 over the parts as a compact ASCII JSON array."""
    parts = prompt_parts(catalog, model_key, lang)
    if parts is None:
        return None
    blob = json.dumps(parts, ensure_ascii=True, separators=(",", ":"))
    return hashlib.sha256(blob.encode("ascii")).hexdigest()


def suite_hash(doc: Any) -> str:
    """``owlbank.prompt_validation.suite_hash``: SHA-256 over the case file as canonical JSON."""
    blob = json.dumps(doc, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(blob.encode("ascii")).hexdigest()


def params_hash(params: Mapping[str, Any]) -> str:
    """``owlbank.prompt_validation.params_hash``: SHA-256 over the entry's :data:`PARAM_KEYS` as
    canonical JSON."""
    blob = json.dumps({k: params[k] for k in PARAM_KEYS}, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(blob.encode("ascii")).hexdigest()


def entry_params(model_id: str, overrides: Mapping[str, Mapping[str, Any]] | None = None) -> dict[str, Any]:
    """The :data:`PARAM_KEYS` parameters ``model_id`` is deployed with, as synth builds its
    ``OWLBANK_MODELS`` entry (``owlbank_infra.config._model_entry``): the resolver's per-model
    defaults (thinking, text_release), then the entry's ``--model-params`` overrides, normalized as
    synth normalizes ``modelParams`` (strings trimmed and lower-cased); ``max_tokens``, unless
    overridden, follows the resulting thinking as synth's does (1000 with reasoning off, else 2000).
    A ``prompt_caching`` override is accepted and not hashed."""
    resolver = _load_resolver()
    out: dict[str, Any] = dict(resolver.default_params(model_id))
    given = (overrides or {}).get(model_id, {})
    for k, v in given.items():
        if k in ("thinking", "text_release") and isinstance(v, str):
            v = v.strip().lower()
        out[k] = v
    if "max_tokens" not in given:
        out["max_tokens"] = resolver.MAX_TOKENS_OFF if out["thinking"] == "off" else resolver.MAX_TOKENS_REASONING
    return {k: out[k] for k in PARAM_KEYS}


@dataclass(frozen=True)
class PromptRecord:
    """A record as ``check_prompts`` reads it: its hashes and ``cases`` (case ID -> ``(runs, passes)``)."""

    prompt_hash: str
    suite_hash: str
    params_hash: str
    cases: dict[str, tuple[int, int]] = field(default_factory=dict)


@dataclass
class PromptRecords:
    """What ``check_prompts`` reads from the repository. ``records`` maps ``(model key, lang)`` to
    the :class:`PromptRecord`; ``suite`` is the case file's hash (``None``: no case file yet),
    ``suite_runs`` its ``runs`` and ``suite_cases`` its case IDs per language; ``error`` a file that
    couldn't be read (every check then FAILs with it)."""

    catalog: PromptCatalogCopy | None = None
    records: dict[tuple[str, str], PromptRecord] = field(default_factory=dict)
    suite: str | None = None
    suite_runs: int = DEFAULT_SUITE_RUNS
    suite_cases: dict[str, tuple[str, ...]] = field(default_factory=dict)
    error: str | None = None

    @property
    def languages(self) -> tuple[str, ...]:
        return self.catalog.languages if self.catalog is not None else ()

    def full_runs(self, record: PromptRecord, lang: str) -> bool:
        """``Record.full_runs``: every case of ``lang`` passed at least the case file's ``runs``."""
        return all(cid in record.cases and record.cases[cid][0] >= self.suite_runs
                   and record.cases[cid][1] == record.cases[cid][0] for cid in self.suite_cases.get(lang, ()))

    def problem(self, model_id: str, lang: str, params: Mapping[str, Any]) -> str | None:
        """Why ``model_id`` with ``params`` (:func:`entry_params`) has no current record in ``lang``
        (``None``: it has one). Validated is ``ValidationFile.is_validated`` with the entry's
        ``params_hash``: a record with the current prompt, suite and parameter hashes and full runs."""
        if self.error is not None or self.catalog is None:
            return self.error or "no catalog"
        key = prompt_model_key(model_id)
        current = prompt_hash(self.catalog, key, lang)
        if current is None:
            return f"no {SYSTEM_KEY_PREFIX}.{key} text in the catalog"
        if self.suite is None:
            return f"no case file ({PROMPT_SUITE_FILE}), so no record can be current"
        record = self.records.get((key, lang))
        if record is None:
            return f"no validation record for {key} ({lang})"
        if record.suite_hash != self.suite:
            return "the record's cases are stale (the case file changed since)"
        if not self.full_runs(record, lang):
            return f"the record is not a full run (a case ran fewer than the case file's {self.suite_runs} runs)"
        if record.prompt_hash != current:
            return "the record's prompt hash is stale (the prompt or a shared block changed since)"
        if record.params_hash != params_hash(params):
            return ("model parameters changed since validation (this entry's thinking, text_release "
                    "or max_tokens differ from the validated run's)")
        return None

    def has_prompt(self, model_id: str, params: Mapping[str, Any]) -> bool:
        """Validated in every catalog language with ``params``: the resolver's ``has_prompt``."""
        return bool(self.languages) and all(self.problem(model_id, lang, params) is None
                                            for lang in self.languages)


def parse_prompt_records(catalog_doc: Any, records_doc: Any, suite_doc: Any | None) -> PromptRecords:
    """The three files' contents (``suite_doc`` ``None``: no case file). ``KeyError``, ``TypeError``
    or ``ValueError`` on a malformed catalog, records or case file."""
    if not isinstance(records_doc, Mapping) or records_doc.get("version") != RECORDS_VERSION:
        raise ValueError(f"{PROMPT_VALIDATION_FILE}: unknown version")
    records: dict[tuple[str, str], PromptRecord] = {}
    for r in records_doc["records"]:
        cases = {str(cid): (int(t["runs"]), int(t["passes"])) for cid, t in r["cases"].items()}
        records[(str(r["model_key"]), str(r["lang"]))] = PromptRecord(
            str(r["prompt_hash"]), str(r["suite_hash"]), str(r["params_hash"]), cases)
    out = PromptRecords(catalog=PromptCatalogCopy(catalog_doc), records=records)
    if suite_doc is not None:
        out.suite = suite_hash(suite_doc)
        out.suite_runs = int(suite_doc.get("runs", DEFAULT_SUITE_RUNS))
        by_lang: dict[str, list[str]] = {}
        for c in suite_doc["cases"]:
            by_lang.setdefault(str(c["lang"]), []).append(str(c["id"]))
        out.suite_cases = {lang: tuple(ids) for lang, ids in by_lang.items()}
    return out


def load_prompt_records(data_dir: Path) -> PromptRecords:
    """Read the catalog, the records and the case file under ``data_dir``; never raises (an
    unreadable file is the ``error`` every prompt check FAILs with)."""
    try:
        catalog_doc = json.loads((data_dir / PROMPT_CATALOG_FILE).read_text(encoding="utf-8"))
        records_doc = json.loads((data_dir / PROMPT_VALIDATION_FILE).read_text(encoding="utf-8"))
        suite_path = data_dir / PROMPT_SUITE_FILE
        suite_doc = json.loads(suite_path.read_text(encoding="utf-8")) if suite_path.exists() else None
        return parse_prompt_records(catalog_doc, records_doc, suite_doc)
    except (OSError, KeyError, TypeError, ValueError, AttributeError) as exc:
        return PromptRecords(error=f"can't read the prompt files in {data_dir}: {type(exc).__name__}")


def check_prompts(prompts: PromptRecords, model_ids: list[str],
                  model_params: Mapping[str, Mapping[str, Any]] | None = None) -> list[Result]:
    """One line per entry and catalog language: PASS with a current record for the entry's
    parameters (:func:`entry_params` of ``model_params``), else FAIL naming
    the entry, the language and why, with the command to run."""
    if not prompts.languages:
        return [Result("Model prompts", False, prompts.error or "the catalog has no languages",
                       f"check {PROMPT_CATALOG_FILE} and {PROMPT_VALIDATION_FILE} in the repository's data/")]
    out: list[Result] = []
    for model_id in model_ids:
        params = entry_params(model_id, model_params)
        for lang in prompts.languages:
            name = f"Model prompt {model_id} ({lang})"
            why = prompts.problem(model_id, lang, params)
            if why is None:
                out.append(Result(name, True, f"validated: {prompt_model_key(model_id)} has a current record"))
            else:
                out.append(Result(name, False, why,
                                  f"run the prompt suite for {model_id} in {lang} with the parameters you deploy "
                                  "it with (scripts/prompt_suite.py --models, from the repository root), commit "
                                  f"its record in data/{PROMPT_VALIDATION_FILE} with the prompt, then reseed; "
                                  "or deploy a list without this entry"))
    return out


def check_agent_texts(prompts: PromptRecords) -> list[Result]:
    """One line: PASS when every published ``agent.*`` text of
    the repository's catalog keeps the placeholder allow-list and both caller-context frames are in
    every catalog language, else FAIL naming each key and language (the seed refuses the same)."""
    name = "Agent prompt texts"
    fix = (f"fix the named texts in data/{PROMPT_CATALOG_FILE} (agent.system.*, the web-activity blocks, "
           "the unverified caller context and any other agent.* text have no placeholders; "
           "agent.caller_context has exactly {firstName}, {memory}, {profile}; both caller-context "
           "frames in every catalog language), then reseed")
    if prompts.catalog is None:
        return [Result(name, False, prompts.error or "no catalog",
                       f"check {PROMPT_CATALOG_FILE} in the repository's data/")]
    problems = agent_text_problems(prompts.catalog)
    if problems:
        return [Result(name, False, "; ".join(problems), fix)]
    return [Result(name, True, "every agent.* text keeps the placeholder allow-list and both "
                   "caller-context frames are in every catalog language")]


