def fetch_agentcore_quotas(quotas: Any) -> dict[str, tuple[float, str]]:
    """``QuotaName -> (value, source)`` for the ``bedrock-agentcore`` quotas named in
    :data:`AGENTCORE_D8_QUOTAS`: the applied value, else the AWS default (``ListServiceQuotas`` lists
    only quotas that have an applied value)."""
    wanted = set(AGENTCORE_D8_QUOTAS)
    found: dict[str, tuple[float, str]] = {}
    for op, source in (("list_service_quotas", "applied"), ("list_aws_default_service_quotas", "AWS default")):
        if wanted <= set(found):
            break
        for page in quotas.get_paginator(op).paginate(ServiceCode=AGENTCORE_QUOTA_SERVICE):
            for q in page.get("Quotas", []):
                qname = q.get("QuotaName")
                if qname in wanted and qname not in found and "Value" in q:
                    found[qname] = (float(q["Value"]), source)
    return found


def _fmt(value: float) -> str:
    return f"{value:,.0f}" if value == int(value) else f"{value:,}"


def default_session_quota(region: str) -> int:
    """``agentcoreSessionQuota``'s default in ``region`` (as ``owlbank_infra.config``)."""
    return AGENTCORE_SESSION_QUOTA_DEFAULTS.get(region, AGENTCORE_SESSION_QUOTA_OTHER_REGIONS)


def check_agentcore_quotas(quotas: Any, region: str, session_quota: int | None = None) -> list[Result]:
    """Print the active-session and new-session-rate quotas next to the sizing rule; WARN when
    ``agentcoreSessionQuota`` (``session_quota``, default the config's for the Region) differs from
    the active-session quota. A missing sizing quota or a failed call is a FAIL."""
    configured = default_session_quota(region) if session_quota is None else session_quota
    name = f"AgentCore quotas ({region})"
    fix = (f"aws service-quotas list-service-quotas --service-code {AGENTCORE_QUOTA_SERVICE} "
           f"--region {region}  (and list-aws-default-service-quotas)")
    try:
        found = fetch_agentcore_quotas(quotas)
    except Exception as exc:
        return [Result(name, False, f"Service Quotas call failed: {_error_code(exc)}", fix)]
    missing = [q for q in (ACTIVE_SESSIONS_QUOTA, NEW_SESSION_RATE_QUOTA) if q not in found]
    if missing:
        return [Result(name, False, "not found in Service Quotas: " + "; ".join(missing), fix)]
    print(f"  AgentCore quotas in {region} (sandbox = measured in the sandbox, us-east-1):")
    for qname, d8 in AGENTCORE_D8_QUOTAS.items():
        if qname in found:
            value, source = found[qname]
            print(f"    {qname}: {_fmt(value)} ({source}; sandbox {d8})")
    print(f"  Sizing rule: {SIZING_RULE}")
    active, rate = found[ACTIVE_SESSIONS_QUOTA][0], found[NEW_SESSION_RATE_QUOTA][0]
    out = [Result(name, True, f"active sessions {_fmt(active)}, new sessions {_fmt(rate)} per second; "
                  f"size by: {SIZING_RULE}")]
    key = "agentcoreSessionQuota"
    label = f"{key} matches the active-session quota"
    if configured != active:
        out.append(Result(label, True,
                          f"{key}={configured:,} but Service Quotas says {_fmt(active)}: the 80 % alarm "
                          f"would fire at {_fmt(0.8 * configured)} sessions instead of {_fmt(0.8 * active)}",
                          f"deploy with -c {key}={int(active)}", warn=True))
    else:
        out.append(Result(label, True, f"{configured:,}"))
    return out


def _error_code(exc: Exception) -> str:
    resp = getattr(exc, "response", None)
    if isinstance(resp, dict):
        return str(resp.get("Error", {}).get("Code", type(exc).__name__))
    return type(exc).__name__


def find_buckets(cloudformation: Any) -> list[tuple[str, str]]:
    """``(stack, bucket name)`` for every S3 bucket in an ``OwlBank*`` stack or ``CDKToolkit``.

    Found through the stacks' resources, not by guessing names. Deleted stacks are not listed by
    ``describe_stacks``; resources that CloudFormation has already deleted are skipped."""
    stacks = sorted(st["StackName"] for page in cloudformation.get_paginator("describe_stacks").paginate()
                    for st in page["Stacks"]
                    if st["StackName"].startswith(STACK_NAME_PREFIX) or st["StackName"] == BOOTSTRAP_STACK)
    found: list[tuple[str, str]] = []
    for stack in stacks:
        for page in cloudformation.get_paginator("list_stack_resources").paginate(StackName=stack):
            for res in page["StackResourceSummaries"]:
                if (res["ResourceType"] == "AWS::S3::Bucket" and res.get("PhysicalResourceId")
                        and not res["ResourceStatus"].startswith("DELETE_")):
                    found.append((stack, res["PhysicalResourceId"]))
    return found


def check_bucket(s3: Any, stack: str, bucket: str) -> Result:
    """Bucket-level Block Public Access (all four on), ownership ``BucketOwnerEnforced``, and a policy
    status that is not public. Reads only; any call that fails is a FAIL, never a skip."""
    name = f"S3 bucket {bucket} ({stack})"
    fix = (f"aws s3api get-public-access-block --bucket {bucket}; if it's off and no SCP forbids it: "
           f"aws s3api put-public-access-block --bucket {bucket} --public-access-block-configuration "
           "BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=true,RestrictPublicBuckets=true")
    problems: list[str] = []
    try:
        conf = s3.get_public_access_block(Bucket=bucket)["PublicAccessBlockConfiguration"]
        off = [k for k in BPA_KEYS if conf.get(k) is not True]
        if off:
            problems.append("Block Public Access off: " + ", ".join(off))
    except Exception as exc:
        code = _error_code(exc)
        problems.append("no bucket-level Block Public Access configuration" if code ==
                        "NoSuchPublicAccessBlockConfiguration" else f"GetPublicAccessBlock failed: {code}")
    try:
        rules = s3.get_bucket_ownership_controls(Bucket=bucket)["OwnershipControls"]["Rules"]
        owners = [r.get("ObjectOwnership") for r in rules]
        if owners != ["BucketOwnerEnforced"]:
            problems.append(f"ownership is {owners}, not BucketOwnerEnforced")
    except Exception as exc:
        code = _error_code(exc)
        problems.append("no ownership controls (ACLs enabled)" if code == "OwnershipControlsNotFoundError"
                        else f"GetBucketOwnershipControls failed: {code}")
    try:
        status = s3.get_bucket_policy_status(Bucket=bucket)["PolicyStatus"]
        if status.get("IsPublic") is not False:
            problems.append("bucket policy is PUBLIC")
    except Exception as exc:
        code = _error_code(exc)
        if code != "NoSuchBucketPolicy":  # no policy at all is not public
            problems.append(f"GetBucketPolicyStatus failed: {code}")
    if problems:
        return Result(name, False, "; ".join(problems), fix)
    return Result(name, True, "Block Public Access all four on, BucketOwnerEnforced, policy not public")


def check_buckets(cloudformation: Any, s3: Any) -> Iterator[Result]:
    try:
        buckets = find_buckets(cloudformation)
    except Exception as exc:
        yield Result("S3 buckets of the OwlBank and CDKToolkit stacks", False,
                     f"could not list stack resources: {_error_code(exc)}",
                     "check the role can call cloudformation:DescribeStacks and ListStackResources")
        return
    if not buckets:
        yield Result("S3 buckets of the OwlBank and CDKToolkit stacks", False,
                     f"no S3 bucket found in {STACK_NAME_PREFIX}* or {BOOTSTRAP_STACK} stacks in this Region",
                     "bootstrap and deploy first, and check --region and --profile")
        return
    for stack, bucket in buckets:
        yield check_bucket(s3, stack, bucket)


def run(*, sts: Any, s3control: Any, bedrock: Any, analyzer: Any | None, stage: str,
        model_id: str = DEFAULT_MODEL, post_deploy: bool = False, ec2: Any | None = None,
        prefix_list_id: str | None = None, secrets: Any | None = None,
        twilio_context: Path | None = None, cloudformation: Any | None = None,
        s3: Any | None = None, az_ec2: Any | None = None, region: str = "us-east-1",
        vpc_azs: tuple[str, ...] | None = None,
        context_file: Path = Path("cdk.context.json"), agentcore_control: Any | None = None,
        quotas: Any | None = None, agentcore_session_quota: int | None = None,
        cloudtrail: Any | None = None, bedrock_for_region: Callable[[str], Any] | None = None,
        slot_mode_ceiling: str = DEFAULT_SLOT_MODE_CEILING,
        logging_regions: tuple[str, ...] | None = None,
        accept_text_logging: bool = False, xray: Any | None = None, logs: Any | None = None,
        call_observability: bool = False, bedrock_runtime: Any | None = None,
        model_ids: list[str] | None = None,
        model_params: dict[str, dict[str, Any]] | None = None,
        prompts: PromptRecords | None = None, strict_account: bool = False) -> list[Result]:
    """``bedrock_runtime`` adds the model list check (:func:`check_models`: resolve and live-test
    ``model_ids``, default the resolved Haiku, Haiku, Sonnet list, with ``model_params`` overrides).
    ``prompts`` adds :func:`check_agent_texts` (the catalog's placeholder line, always) and :func:`check_prompts` on the list to deploy (the resolved list, else ``model_ids``,
    else the default list), each entry with its parameters (``model_params`` over the resolver's
    defaults), and makes the resolver skip a replacement without validated prompts for its
    parameters.
    The invocation-logging and CloudTrail checks always run, before and after a deploy:
    ``bedrock_for_region`` gives a Bedrock client per Region (default: ``bedrock`` for ``region``,
    none elsewhere, which fails closed), ``logging_regions`` the Regions besides ``region`` (default
    :data:`LOGGING_REGIONS`, none), ``accept_text_logging`` turns the logging FAIL into a WARN (never
    at ``stage`` prod: ``ValueError``), and a missing ``cloudtrail`` client counts as no trail.
    ``agentcore_control`` adds the AgentCore Runtime availability check and, when it passes and
    ``quotas`` is given, the quota report (``--agentcore``);
    ``az_ec2`` adds the AgentCore AZ check and caches the AZ map (``--agentcore``);
    ``ec2`` and ``prefix_list_id`` add the prefix list check (CloudFront mode); ``secrets`` and
    ``twilio_context`` add the first-deploy checks of ``--before-bridge``; ``cloudformation`` and
    ``s3`` are needed by ``post_deploy`` (the bucket check); ``call_observability`` with the
    ``xray`` and ``logs`` clients adds the Transaction Search check (``--call-observability``);
    ``strict_account`` makes the Access Analyzer check fail on any finding in the account, not only
    those on this blueprint's resources."""
    if accept_text_logging and stage == "prod":
        raise ValueError("--accept-text-logging is refused at stage prod")
    account = sts.get_caller_identity()["Account"]
    results = [check_s3_public_access_block(s3control, account)]
    results += check_inference_profile(bedrock, model_id)
    deploy_ids = model_ids or None
    if bedrock_runtime is not None:
        has_prompt = None if prompts is None else (
            lambda mid: prompts.has_prompt(mid, entry_params(mid, model_params)))
        res = resolve_list(bedrock, bedrock_runtime, region, model_ids, model_params, has_prompt=has_prompt)
        results += model_results(res)
        deploy_ids = res.model_ids or None
        for i, r in enumerate(results):
            if r.name == f"Bedrock model access {model_id.split('.', 1)[-1]}":
                results[i] = recheck_model_access(r, bedrock, model_id, res.model_ids)
    if prompts is not None:
        results += check_agent_texts(prompts)
        if deploy_ids is None and bedrock_runtime is None:
            deploy_ids = default_list_ids(region)
        if deploy_ids:
            results += check_prompts(prompts, deploy_ids, model_params)
    if bedrock_for_region is None:
        def bedrock_for_region(r: str) -> Any:
            return bedrock if r == region else None
    results += check_invocation_logging(bedrock_for_region, slot_mode_ceiling,
                                        _logging_regions(region, logging_regions),
                                        accept_text_logging=accept_text_logging)
    results.append(check_management_trail(cloudtrail, region, stage))
    if call_observability and xray is not None and logs is not None:
        results.append(check_transaction_search(xray, logs, region, account))
    if ec2 is not None and prefix_list_id:
        results.append(check_cloudfront_prefix_list(ec2, prefix_list_id))
    if agentcore_control is not None:
        available = check_agentcore_available(agentcore_control, region)
        results.append(available)
        if available.ok and quotas is not None:
            results += check_agentcore_quotas(quotas, region, agentcore_session_quota)
    if az_ec2 is not None:
        results += check_agentcore_azs(az_ec2, account, region,
                                       vpc_azs or (f"{region}a", f"{region}b"), context_file)
    if secrets is not None:
        results += check_secrets_populated(secrets)
        results += check_context_api_key_written(secrets)
    if twilio_context is not None:
        results.append(check_twilio_context(twilio_context))
    if post_deploy:
        if analyzer is None:
            raise ValueError("--post-deploy needs the Access Analyzer client")
        if cloudformation is None or s3 is None:
            raise ValueError("--post-deploy needs the CloudFormation and S3 clients")
        results += check_buckets(cloudformation, s3)
        own_ids: set[str] | None
        reason: str | None = None
        try:
            own_ids = own_resource_ids(cloudformation)
        except Exception as exc:  # noqa: BLE001 - reported unfiltered, with the reason
            own_ids, reason = None, _error_code(exc)
        results.append(check_access_analyzer(analyzer, f"owlbank-{stage}-account", own_ids,
                                             strict=strict_account, unscoped_reason=reason))
    return results


def report(results: list[Result]) -> int:
    for r in results:
        print(f"[{'FAIL' if not r.ok else 'WARN' if r.warn else 'PASS'}] {r.name}: {r.detail}")
        if (not r.ok or r.warn) and r.fix:
            print(f"       fix (run it yourself): {r.fix}")
    return 0 if all(r.ok for r in results) else 1


