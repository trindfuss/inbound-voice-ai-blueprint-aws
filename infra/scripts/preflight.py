    ap.add_argument("--prefix-list-id", default=DEFAULT_PREFIX_LIST_ID,
                    help="cloudFrontOriginPrefixListId to verify (CloudFront mode)")
    ap.add_argument("--no-prefix-list", action="store_true", help="custom-domain mode: skip the prefix list check")
    ap.add_argument("--before-bridge", action="store_true",
                    help="after OwlBankData, before the other stacks: secrets populated, Twilio output present")
    ap.add_argument("--twilio-context", type=Path, default=Path("twilio.context.json"),
                    help="twilio_setup.py --output file (default: twilio.context.json, run from infra/)")
    ap.add_argument("--slot-mode-ceiling", default=DEFAULT_SLOT_MODE_CEILING, choices=SLOT_MODES,
                    help="the slotModeCeiling you deploy with: deterministic turns the invocation-logging "
                         "FAIL into a WARN (default: assisted)")
    ap.add_argument("--logging-regions", default="",
                    help="extra Regions whose Bedrock invocation logging is read besides --region "
                         "(default: none; the source Region's configuration is the one that applies)")
    ap.add_argument("--accept-text-logging", action="store_true",
                    help="dev/test only (refused with --stage prod): WARN instead of FAIL when invocation "
                         "logging delivers text, for a trusted sandbox where test speech may be logged")
    ap.add_argument("--strict-account", action="store_true",
                    help="with --post-deploy: fail on any ACTIVE Access Analyzer finding in the account "
                         "(default: only findings on this blueprint's resources; others are a note)")
    ap.add_argument("--agentcore", action="store_true",
                    help="AgentCore hosting: Runtime offered in the Region, its quotas, and (VPC mode) "
                         "cache the AZ name -> ID map and check the VPC's AZ IDs")
    ap.add_argument("--agentcore-session-quota", type=int, default=None,
                    help="the agentcoreSessionQuota you deploy with (default: the config default for the Region)")
    ap.add_argument("--availability-zones", default="",
                    help="the VPC's AZ names when availabilityZones is set (default <region>a,<region>b)")
    ap.add_argument("--call-observability", action="store_true",
                    help="callObservability=on: check X-Ray Transaction Search (destination "
                         "CloudWatchLogs ACTIVE, X-Ray's resource policy on aws/spans)")
    ap.add_argument("--context-file", type=Path, default=Path("cdk.context.json"),
                    help="CDK context file the AZ map is cached in (default: cdk.context.json, run from infra/)")
    args = ap.parse_args(argv)
    if args.accept_text_logging and args.stage == "prod":
        ap.error("--accept-text-logging is refused with --stage prod")
    vpc_azs = tuple(n.strip() for n in args.availability_zones.split(",") if n.strip()) or None
    regions = tuple(n.strip() for n in args.logging_regions.split(",") if n.strip()) or None
    import boto3  # noqa: PLC0415

    session = boto3.Session(profile_name=args.profile, region_name=args.region)
    bedrock = session.client("bedrock")
    bedrock_clients = {args.region: bedrock}

    def bedrock_for_region(r: str) -> Any:
        if r not in bedrock_clients:
            bedrock_clients[r] = session.client("bedrock", region_name=r)
        return bedrock_clients[r]

    results = run(sts=session.client("sts"), s3control=session.client("s3control"),
                  bedrock=bedrock, bedrock_for_region=bedrock_for_region,
                  cloudtrail=session.client("cloudtrail"), slot_mode_ceiling=args.slot_mode_ceiling,
                  logging_regions=regions, accept_text_logging=args.accept_text_logging,
                  analyzer=session.client("accessanalyzer") if args.post_deploy else None,
                  cloudformation=session.client("cloudformation") if args.post_deploy else None,
                  s3=session.client("s3") if args.post_deploy else None,
                  stage=args.stage, model_id=args.model_id, post_deploy=args.post_deploy,
                  ec2=None if args.no_prefix_list else session.client("ec2"),
                  prefix_list_id=args.prefix_list_id,
                  secrets=session.client("secretsmanager") if args.before_bridge else None,
                  twilio_context=args.twilio_context if args.before_bridge else None,
                  az_ec2=session.client("ec2") if args.agentcore else None, region=args.region,
                  vpc_azs=vpc_azs, context_file=args.context_file,
                  agentcore_control=session.client("bedrock-agentcore-control") if args.agentcore else None,
                  quotas=session.client("service-quotas") if args.agentcore else None,
                  agentcore_session_quota=args.agentcore_session_quota,
                  call_observability=args.call_observability,
                  bedrock_runtime=None if args.no_resolve_models else session.client("bedrock-runtime"),
                  model_ids=args.model_list, model_params=json.loads(args.model_params),
                  prompts=load_prompt_records(args.data_dir), strict_account=args.strict_account,
                  xray=session.client("xray") if args.call_observability else None,
                  logs=session.client("logs") if args.call_observability else None)
    return report(results)


