def fetch_az_map(ec2: Any) -> dict[str, str]:
    """The Region's AZ name -> AZ ID map for this account (read-only ``DescribeAvailabilityZones``;
    zones of type ``availability-zone`` only, not Local or Wavelength Zones)."""
    zones = ec2.describe_availability_zones(
        Filters=[{"Name": "zone-type", "Values": ["availability-zone"]}])["AvailabilityZones"]
    return {z["ZoneName"]: z["ZoneId"] for z in zones}


def cache_az_map(path: Path, account: str, region: str, az_map: dict[str, str]) -> str:
    """Write ``az_map`` into the CDK context file at ``owlbank:az-ids:<account>:<region>``, keeping
    every other key; atomic (temp file + rename). Returns the key. A file that isn't a JSON object
    is left alone (``ValueError``)."""
    key = f"{AZ_IDS_CONTEXT_PREFIX}:{account}:{region}"
    doc: dict[str, Any] = {}
    if path.exists():
        doc = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(doc, dict):
            raise ValueError(f"{path} is not a JSON object")
    doc[key] = dict(sorted(az_map.items()))
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            json.dump(doc, fh, indent=2, sort_keys=True)
            fh.write("\n")
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    return key


def check_agentcore_azs(ec2: Any, account: str, region: str, vpc_azs: tuple[str, ...],
                        context_file: Path,
                        supported: tuple[str, ...] | None = None) -> list[Result]:
    """Cache the AZ map, then check the VPC's AZ names against AgentCore's supported AZ IDs."""
    supported = AGENTCORE_SUPPORTED_AZ_IDS.get(region, ()) if supported is None else supported
    az_map = fetch_az_map(ec2)
    out: list[Result] = []
    cached = f"AZ ID map cached in {context_file}"
    if not az_map:
        out.append(Result(cached, False, f"DescribeAvailabilityZones returned no AZs for {region}",
                          "check --region and --profile"))
    else:
        try:
            key = cache_az_map(context_file, account, region, az_map)
            out.append(Result(cached, True, f"{len(az_map)} AZs under {key}"))
        except (OSError, ValueError) as exc:
            out.append(Result(cached, False, str(exc), "fix or remove the file, then rerun preflight"))
    name = f"AgentCore VPC mode AZ IDs ({region})"
    if not supported:
        return out + [Result(name, False, f"no supported AZ IDs listed for {region}",
                             "add the Region's list from the AgentCore docs to AGENTCORE_SUPPORTED_AZ_IDS "
                             "(config.py and preflight.py), or use agentcoreNetworkMode=public")]
    missing = [n for n in vpc_azs if n not in az_map]
    if missing:
        return out + [Result(name, False, f"{', '.join(missing)} not an AZ of {region} in this account",
                             "fix availabilityZones (and --availability-zones)")]
    ours = ", ".join(f"{n} ({az_map[n]})" for n in vpc_azs)
    good = [n for n in vpc_azs if az_map[n] in supported]
    if len(good) == len(vpc_azs):
        return out + [Result(name, True, f"{ours}: all supported")]
    if good:
        return out + [Result(name, True, f"{ours}; only {', '.join(good)} supported: the Runtime runs "
                             "in one AZ (stage prod needs agentcoreSingleAzAck=true)")]
    candidates = sorted(n for n, i in az_map.items() if i in supported)
    return out + [Result(name, False, f"{ours}; supported AZ IDs are {', '.join(supported)}",
                         f"set availabilityZones to two of {', '.join(candidates) or '(none in this account)'} "
                         "(this replaces the VPC), or use agentcoreNetworkMode=public")]


