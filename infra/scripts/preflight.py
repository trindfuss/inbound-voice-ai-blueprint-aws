#!/usr/bin/env python3
"""Read-only account checks around a deploy. Never changes anything in AWS; it reports, and
prints the command the owner would run to fix a failure.

Before a deploy::

    uv run python scripts/preflight.py --profile <profile> --stage dev

* Account-level S3 Block Public Access: all four settings on (CloudFormation can't set it).
* Bedrock: the inference profile's destination Regions all lie in the profile's
  geography (``us.`` -> ``us-*``), and the model is authorized in the source Region.

* Bedrock model-invocation logging: in the deployment Region, whose configuration
  applies to every call through the ``us.`` profile wherever it runs (``--logging-regions``
  adds others), no configuration, or ``textDataDeliveryEnabled`` false. Otherwise FAIL (WARN with
  ``--slot-mode-ceiling deterministic``, or with ``--accept-text-logging`` in dev or test, never prod):
  the resolver's prompts would be logged with callers' digits.
  Messages name fields only, never a bucket, log group or content.
* CloudTrail: a trail that is logging records management write events in the Region, so
  EventBridge gets ``PutModelInvocationLoggingConfiguration`` and the alarm can fire. Otherwise
  WARN in dev and test, FAIL at ``--stage prod``. Both checks run again under ``--post-deploy``.

* CloudFront mode: the managed prefix list ``com.amazonaws.global.cloudfront.origin-facing``
  has the ID that ``cloudFrontOriginPrefixListId`` carries (``--prefix-list-id``).

After ``OwlBankData`` is deployed and before any other stack (the first-deploy order)::

    uv run python scripts/preflight.py --profile <profile> --stage dev --before-bridge

* The two operator-written Twilio secrets (``owlbank/twilio/api-key``, ``owlbank/twilio/auth-token``)
  have been written, not just created: the bridge's tasks fail to start on the placeholder (a missing
  JSON key), so deploying ``OwlBankBridge`` first would roll back. Judged from the version stages,
  never by reading a value: a created secret has one version; a written one also has ``AWSPREVIOUS``.
  ``owlbank/twilio/basic-auth`` is generated by Secrets Manager at the Data deploy and no one writes
  it, so it passes with a current (``AWSCURRENT``) version. Any of the three scheduled for deletion
  fails. Form and readability are ``check_secrets.py``'s job (it reads the values; first deploy, step 6).
* ``infra/twilio.context.json`` (``--twilio-context``) holds ``verifyServiceSid`` and
  ``conversationConfigurationId`` from ``twilio_setup.py --phase pre``: the bridge needs the
  configuration ID at startup and ``auth_service`` the Verify SID.

After a deploy::

    uv run python scripts/preflight.py --profile <profile> --stage dev --post-deploy

* Also: the stack's IAM Access Analyzer (``owlbank-<stage>-account``) has no ACTIVE
  findings on the blueprint's own resources (those of the ``OwlBank*`` stacks, found through
  their resources), so nothing of ours is shared outside the account. Findings on other resources in
  a shared account are a note with their count; ``--strict-account`` fails on any finding.
* Every S3 bucket that the ``OwlBank*`` stacks or the CDK bootstrap stack (``CDKToolkit``) created
  (found through the stacks' resources, never by name): bucket-level Block Public Access reads all four
  settings true, ownership is ``BucketOwnerEnforced``, and ``GetBucketPolicyStatus`` says not public.
  This is the check that matters with ``s3PublicAccessBlockMode=account`` (an organization SCP denies
  ``s3:PutBucketPublicAccessBlock``, so the template can't set it and S3's default for new buckets
  is what protects them). Any bucket that fails, and finding no bucket at all, is a FAIL.

Call observability, with ``callObservability=on``::

    uv run python scripts/preflight.py --profile <profile> --stage dev --call-observability

* X-Ray Transaction Search: the trace segment destination is ``CloudWatchLogs`` and ``ACTIVE``
  (``PENDING`` WARNs: it activates within minutes) and a CloudWatch Logs resource policy lets
  ``xray.amazonaws.com`` ``logs:PutLogEvents`` into ``aws/spans``. Otherwise FAIL with the two
  commands that enable it. It is account-wide (every X-Ray trace in the Region), so preflight never
  enables it; ``tracesEnableTransactionSearch=true`` lets the stack do so in a dedicated account.

Model list, always, before the stacks::

    uv run python scripts/preflight.py --profile <profile> --stage dev [--list-model <profile id> ...] [--no-resolve-models]

* ``resolve_models.py`` lists the ACTIVE Anthropic models and the Region's geography profiles, sends
  one synthetic one-token request to each list entry (the real test), replaces a failing entry by the
  next lower version of its series (WARN), and prints the final list with the ``-c modelIds=[...]`` to
  deploy with. FAIL: an entry with no working replacement, another geography's profile, an invalid
  parameter set, or no working entry. WARN: a ``global.`` entry, a LEGACY model (with its end-of-life date).
* Per-model prompts, read from the repository (``--data-dir``, default
  the repo's ``data/``), no AWS call: for each entry of the list to deploy (the resolved list; with
  ``--no-resolve-models`` the ``--list-model`` entries or the default list) and each catalog language,
  PASS when ``prompt_validation.json`` holds a record with the current prompt hash, the current
  ``prompt_suite.json`` hash, full runs (every case at least the case file's ``runs``) and the hash of
  the entry's parameters (thinking, text_release, max_tokens: the resolver's defaults and
  ``--model-params``; not prompt caching, which changes cost and latency, not the answer), else FAIL naming the entry, the language and why (no
  record, prompt, cases or model parameters changed since, too few runs, no text in the catalog). A
  replacement without validated prompts in every language is never proposed. The prompt and
  parameter hashes and the record reader are this script's own copies of ``owlbank.agent_prompt`` and
  ``owlbank.prompt_validation``, pinned by ``tests/unit/test_failover_parity.py``.
  With them, one "Agent prompt texts" line FAILs when a published
  ``agent.*`` text breaks the placeholder allow-list (a copy of ``owlbank.agent_prompt``'s) or a
  caller-context frame is missing in a catalog language, naming each key and language, as the seed does.

AgentCore hosting, before synth of ``bridgeHosting=agentcore``::

    uv run python scripts/preflight.py --profile <profile> --stage dev --agentcore \
        [--agentcore-session-quota <the agentcoreSessionQuota you deploy with>]

* AgentCore Runtime is offered in the Region: the Region is in the AgentCore Regions table and a
  read-only ``ListAgentRuntimes`` probe answers. Either failing is a FAIL naming the Region.
* Prints the account's active-session and new-session-rate quotas (Service Quotas, service code
  ``bedrock-agentcore``; the AWS default when no applied value is listed) next to the sizing rule,
  and WARNs when ``agentcoreSessionQuota`` differs from the active-session quota (it is the
  basis of the 80 % alarm). The fixed quotas the design relies on (streaming duration, WebSocket
  frame size and rate) and the data-plane rate are listed with the values measured in.
* Reads the account's AZ name -> AZ ID map (``DescribeAvailabilityZones``) and caches it in
  ``cdk.context.json`` (``--context-file``, run from infra/) under
  ``owlbank:az-ids:<account>:<region>``; synth reads it there and never guesses. That file holds the
  account ID, so it is git-ignored. Writing it is the only local change preflight makes.
* Checks the VPC's AZ names (``--availability-zones``, default ``<region>a,<region>b``) against the
  AZ IDs AgentCore VPC mode supports: both -> PASS; one -> PASS with the single-AZ warning (stage
  prod then needs ``agentcoreSingleAzAck=true``); none -> FAIL naming the AZ names that would work.

Calls (all read-only, except the one-token model requests): sts:GetCallerIdentity, ec2:DescribeAvailabilityZones,
bedrock-agentcore:ListAgentRuntimes, servicequotas:ListServiceQuotas,
servicequotas:ListAWSDefaultServiceQuotas, s3:GetAccountPublicAccessBlock,
cloudformation:DescribeStacks, cloudformation:ListStackResources, s3:GetBucketPublicAccessBlock,
s3:GetBucketOwnershipControls, s3:GetBucketPolicyStatus,
bedrock:GetInferenceProfile, bedrock:GetFoundationModelAvailability,
bedrock:ListFoundationModels, bedrock:ListInferenceProfiles, bedrock-runtime:Converse (one token, no
caller data, per model list entry),
bedrock:GetModelInvocationLoggingConfiguration, cloudtrail:DescribeTrails, cloudtrail:GetTrailStatus,
cloudtrail:GetEventSelectors,
access-analyzer:ListAnalyzers, access-analyzer:ListFindings,
ec2:DescribeManagedPrefixLists, secretsmanager:DescribeSecret,
xray:GetTraceSegmentDestination, logs:DescribeResourcePolicies.
Clients are injected (``run``), so the tests use botocore's Stubber and no AWS account.
"""

